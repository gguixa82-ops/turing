/* ============ registry, detection, lookup ============ */

const LANGS = [
  { code: 'en',    native: 'English',              dict: en },
  { code: 'fr',    native: 'Français',             dict: fr },
  { code: 'de',    native: 'Deutsch',              dict: de },
  { code: 'hi',    native: 'हिन्दी',                  dict: hi },
  { code: 'id',    native: 'Bahasa Indonesia',     dict: id },
  { code: 'it',    native: 'Italiano',             dict: it },
  { code: 'ja',    native: '日本語',                dict: ja },
  { code: 'ko',    native: '한국어',                dict: ko },
  { code: 'pt-BR', native: 'Português (Brasil)',   dict: ptBR },
  { code: 'es-419', native: 'Español (Latinoamérica)', dict: es419 },
  { code: 'es-ES', native: 'Español (España)',     dict: esES },
];
const BY_CODE = Object.fromEntries(LANGS.map(l => [l.code, l]));
const SUPPORTED = LANGS.map(l => l.code);

function detectLang() {
  try {
    const saved = localStorage.getItem('turing_lang');
    if (saved && SUPPORTED.includes(saved)) return saved;
  } catch {}
  const candidates = (typeof navigator !== 'undefined' && navigator.languages && navigator.languages.length)
    ? navigator.languages
    : [(typeof navigator !== 'undefined' && navigator.language) || 'en'];
  for (const raw of candidates) {
    const l = String(raw).toLowerCase();
    for (const c of SUPPORTED) if (c.toLowerCase() === l) return c;
    if (l.startsWith('es')) return l === 'es-es' || l === 'es' ? 'es-ES' : 'es-419';
    if (l.startsWith('pt')) return 'pt-BR';
    const base = l.split('-')[0];
    const hit = SUPPORTED.find(c => c.toLowerCase().split('-')[0] === base);
    if (hit) return hit;
  }
  return 'en';
}

function dictFor(code) { return (BY_CODE[code] || BY_CODE.en).dict; }
function t(code, key, vars) {
  let v = dictFor(code)[key];
  if (v === undefined) v = en[key];
  if (v === undefined) return key;
  if (vars && typeof v === 'string') v = v.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? vars[k] : m));
  return v;
}

return { LANGS, SUPPORTED, detectLang, t, dictFor };
